# Ejercicio 10: Promedio de peso de tres personas
p1 = float(input("Ingrese el peso de la primera persona: "))
p2 = float(input("Ingrese el peso de la segunda persona: "))
p3 = float(input("Ingrese el peso de la tercera persona: "))
promedio = (p1 + p2 + p3) / 3
print("El promedio de peso es:", promedio)
